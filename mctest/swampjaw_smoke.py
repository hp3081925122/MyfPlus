command(f"tp @s {x} {y} {z} 0 35")
sleep(1)

for fx in ["warn_line", "warn_circle", "sj_ambush_ring", "sj_slam", "sj_geyser", "sj_splash", "sj_bubble_pop"]:
    command(f"myfplus fx {fx} 3")
    sleep(0.6)
    screenshot(f"fx_{fx}")
    command("kill @e[type=myfplus:fx]")

command("gamemode survival")
command("effect give @s resistance 1000 3 true")
command("effect give @s regeneration 1000 2 true")
command(f"summon meetyourfight:swampjaw {x} {y + 6} {z + 10}")
sleep(3)
boss = entities(40, "meetyourfight:swampjaw")
expect(len(boss) == 1, f"swampjaw spawned: {boss}")
print("boss", boss)

def run_skill(name, wait, shots=2):
    command(f"myfplus skill {name}")
    for i in range(shots):
        sleep(wait / shots)
        b = entities(40, "meetyourfight:swampjaw")
        if b:
            look(at=(b[0]["x"], b[0]["y"], b[0]["z"]))
        screenshot(f"skill_{name}_{i}")

run_skill("mud", 3.0)
pits = entities(40, "myfplus:mud_pit")
print("pits", len(pits))
expect(len(pits) >= 3, f"mud pits created: {len(pits)}")
look(0, 60)
screenshot("mud_pits_ground")
run_skill("hook", 3.0)
run_skill("dash", 2.5)
